"""Markdown compliance report writer: ``docs/compliance_report.md``."""

from __future__ import annotations

from collections.abc import Mapping

from nordic_bess.compliance.evaluate import RequirementResult
from nordic_bess.config import Config


def _fmt(value: float) -> str:
    return f"{value:.3f}" if abs(value) < 1000 else f"{value:.0f}"


def _cell(text: str) -> str:
    """Escape pipes (as in |dP_th|) so they do not split Markdown table cells."""
    return text.replace("|", r"\|")


def results_markdown(results: list[RequirementResult]) -> str:
    """Requirement / measured / threshold / pass table."""
    lines = [
        "| Requirement | Product | Measured | Threshold | Pass | Explanation |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        unit = f" {r.unit}" if r.unit and r.unit not in ("p.u.", "steps") else ""
        lines.append(
            f"| {r.requirement} | {r.product} | {_fmt(r.measured)}{unit} | {_cell(r.threshold)} | "
            f"{'PASS' if r.passed else 'FAIL'} | {_cell(r.explanation)} |"
        )
    return "\n".join(lines)


def write_report(
    cfg: Config,
    results: list[RequirementResult],
    figures: Mapping[str, str],
    title: str = "Compliance report",
    unit_description: str | None = None,
) -> str:
    """Full report text. ``figures`` maps captions to paths relative to ``docs/``."""
    b, c = cfg.bess, cfg.compliance
    n_pass = sum(r.passed for r in results)
    unit = unit_description or (
        f"the Python BESS model, {b.p_max_mw:g} MW / {b.e_nom_mwh:g} MWh, usable window "
        f"{b.soc_min:.0%}-{b.soc_max:.0%}, converter time constant "
        f"{b.converter_time_constant_s:g} s, per-product droop controllers with NEM and AEM."
    )
    parts = [
        f"# {title}",
        "",
        "Generated by `scripts/run_compliance.py` from `configs/base.yaml`. Do not edit by hand.",
        "",
        "Requirements: *Technical Requirements for Frequency Containment Reserve Provision in "
        f"the Nordic Synchronous Area*, version {cfg.fcr.version} (see docs/FCR_SPEC_NOTES.md).",
        "",
        f"Unit under test: {unit}",
        "",
        f"Tested capacities: FCR-N {c.c_fcr_n_mw:g} MW, FCR-D up {c.c_fcr_dup_mw:g} MW, "
        f"FCR-D down {c.c_fcr_ddown_mw:g} MW, each product tested alone from the target SOC.",
        "",
        f"Result: {n_pass} of {len(results)} checks pass.",
        "",
        results_markdown(results),
        "",
        "## Method notes",
        "",
        f"- Steady-state power P_ss is the mean over the last {c.steady_state_window_s:g} s "
        "of each hold (the requirements do not fix the window).",
        "- Requirements 2 and 3 use the power change from the start of ramp 5; Requirement 4 "
        "the change from the start of ramp 1, with the nadir 4.4 s after it.",
        "- 'R2 hold' checks that the power does not drop below dP(7.5 s) before ramp 6; small "
        "damped oscillations are accepted, implemented as a 1 % of |dP_th| tolerance.",
        "- Frequency domain: F(jw) from least-squares sine fits of the last stationary periods "
        "of each Table 6 test; G0 = F G with the Table 7 stability parameters (sign convention "
        "resolved in docs/FCR_SPEC_NOTES.md); Requirement 9 is checked on a log-spaced grid "
        "interpolated between the tested periods.",
        "- The test signal is applied to the controller input directly, so no frequency "
        "measurement equipment transfer function (section 4.4) is included.",
        "- LER tests (Tables 12-13) hold each step for its minimum duration and until its "
        f"condition holds; they start {c.ler_start_margin_min:g} min of full activation before "
        "the NEM threshold, as section 3.5.3 allows to shorten the test.",
        "",
        "## Figures",
        "",
    ]
    for caption, path in figures.items():
        parts += [f"### {caption}", "", f"![{caption}]({path})", ""]
    return "\n".join(parts)
