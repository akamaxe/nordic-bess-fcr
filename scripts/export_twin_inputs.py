"""Export parameters and test signals for the Simulink digital twin.

Writes simulink/inputs/params.json (battery, FCR and twin parameters from the config)
and one CSV per test signal (t_s, f_hz) generated by nordic_bess.compliance.signals,
plus simulink/inputs/manifest.json listing product and tested capacity per signal.
MATLAB then runs simulink/run_twin.m and scripts/evaluate_twin.py scores the output.

Usage: uv run python scripts/export_twin_inputs.py --config configs/base.yaml
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from nordic_bess.compliance.runner import tested_capacity
from nordic_bess.compliance.signals import fcr_d_ramp_sequence, fcr_n_step_sequence
from nordic_bess.config import Config, load_config
from nordic_bess.spec import Product


def twin_params(cfg: Config) -> dict:
    b, f, sim = cfg.bess, cfg.fcr, cfg.simulation
    dt = sim.test_signal_step_s
    return {
        "dt_s": dt,
        "steps_per_tick": int(round(1.0 / dt)),
        "window_samples": f.nem_window_s,
        "p_max_mw": b.p_max_mw,
        "e_nom_mwh": b.e_nom_mwh,
        "e_min_mwh": b.e_min_mwh,
        "e_max_mwh": b.e_max_mwh,
        "e0_mwh": b.e_target_mwh,
        "eta_c": b.eta_charge,
        "eta_d": b.eta_discharge,
        "tau_s": b.converter_time_constant_s,
        "nem_rate_n": f.nem_rate_n,
        "nem_rate_d": f.nem_rate_d,
        "energy_hours_d": f.energy_hours_d,
        "min_n": [
            f.thresholds_fcr_n.aem_enable,
            f.thresholds_fcr_n.aem_disable,
            f.thresholds_fcr_n.nem_enable,
            f.thresholds_fcr_n.nem_disable,
        ],
        "min_d": [
            f.thresholds_fcr_d.aem_enable,
            f.thresholds_fcr_d.aem_disable,
            f.thresholds_fcr_d.nem_enable,
            f.thresholds_fcr_d.nem_disable,
        ],
        "dc_voltage_v": cfg.twin.dc_voltage_v,
        "internal_resistance_ohm": cfg.twin.internal_resistance_ohm,
    }


def signals(cfg: Config):
    dt = cfg.simulation.test_signal_step_s
    yield fcr_n_step_sequence(dt)
    yield fcr_d_ramp_sequence(Product.FCR_D_UP, dt)
    yield fcr_d_ramp_sequence(Product.FCR_D_DOWN, dt)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default="configs/base.yaml")
    parser.add_argument("--out", default="simulink/inputs")
    args = parser.parse_args()
    cfg = load_config(args.config)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "params.json").write_text(json.dumps(twin_params(cfg), indent=2), encoding="utf-8")
    manifest = []
    for sig in signals(cfg):
        c = tested_capacity(cfg, sig.product)
        caps = [c if sig.product is p else 0.0 for p in Product]
        np.savetxt(
            out / f"{sig.name}.csv",
            np.column_stack([sig.t_s, sig.f_hz]),
            delimiter=",",
            header="t_s,f_hz",
            comments="",
            fmt="%.6f",
        )
        manifest.append({"name": sig.name, "product": sig.product.value, "caps_mw": caps})
        print(f"exported {sig.name}: {len(sig.t_s)} samples, caps {caps}")
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
